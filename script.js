let examState = {
    questions: [],
    currentIndex: 0,
    answers: {},
    marked: {},
    startTime: null,
    timerInterval: null,
    timeLimit: 0,
    timeElapsed: 0,
    examActive: false
};

function shuffleArray(arr) {
    const a = [...arr];
    for (let i = a.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
}

function getAllQuestions() {
    const sample = typeof sampleQuestions !== 'undefined' ? sampleQuestions : [];
    const authored = typeof authoredQuestions !== 'undefined' ? authoredQuestions : [];
    return [...sample, ...authored];
}

function setupExam() {
    const topic = document.getElementById('exam-topic').value;
    const difficulty = document.getElementById('exam-difficulty').value;
    const count = document.getElementById('exam-count').value;
    const source = document.getElementById('exam-source').value;
    const timer = parseInt(document.getElementById('exam-timer').value);

    let pool = getAllQuestions();
    if (source === 'sample') pool = sampleQuestions;
    if (source === 'authored') pool = (typeof authoredQuestions !== 'undefined') ? authoredQuestions : [];

    if (topic !== 'all') pool = pool.filter(q => q.topic === topic);
    if (difficulty !== 'all') pool = pool.filter(q => q.difficulty === difficulty);

    if (pool.length === 0) {
        document.getElementById('setup-message').textContent = 'هیچ سؤالی با این فیلترها یافت نشد.';
        return;
    }

    let selected;
    if (count === 'all') {
        selected = shuffleArray(pool);
    } else {
        const n = Math.min(parseInt(count), pool.length);
        selected = shuffleArray(pool).slice(0, n);
    }

    examState.questions = selected.map(q => ({
        ...q,
        shuffledOptions: shuffleArray(q.options.map((opt, i) => ({ text: opt, originalIndex: i })))
    }));

    examState.currentIndex = 0;
    examState.answers = {};
    examState.marked = {};
    examState.startTime = Date.now();
    examState.timeLimit = timer * 60;
    examState.timeElapsed = 0;
    examState.examActive = true;

    document.getElementById('exam-setup').classList.add('hidden');
    document.getElementById('exam-running').classList.remove('hidden');
    document.getElementById('exam-result').classList.add('hidden');

    renderExamQuestion();
    renderPalette();
    startTimer();
}

function startTimer() {
    if (examState.timerInterval) clearInterval(examState.timerInterval);
    updateTimerDisplay();
    examState.timerInterval = setInterval(() => {
        examState.timeElapsed++;
        updateTimerDisplay();
        if (examState.timeLimit > 0 && examState.timeElapsed >= examState.timeLimit) {
            clearInterval(examState.timerInterval);
            finishExam(true);
        }
    }, 1000);
}

function updateTimerDisplay() {
    const display = document.getElementById('exam-timer-display');
    if (!display) return;
    let secondsLeft;
    if (examState.timeLimit > 0) {
        secondsLeft = Math.max(0, examState.timeLimit - examState.timeElapsed);
    } else {
        secondsLeft = examState.timeElapsed;
    }
    const m = Math.floor(secondsLeft / 60).toString().padStart(2, '0');
    const s = (secondsLeft % 60).toString().padStart(2, '0');
    display.textContent = `${m}:${s}`;
    display.classList.remove('warning', 'danger');
    if (examState.timeLimit > 0) {
        if (secondsLeft < 60) display.classList.add('danger');
        else if (secondsLeft < 180) display.classList.add('warning');
    }
}

function renderExamQuestion() {
    const q = examState.questions[examState.currentIndex];
    if (!q) return;
    const container = document.getElementById('exam-question-container');
    const diffLabel = q.difficulty === 'easy' ? 'آسان' : q.difficulty === 'medium' ? 'متوسط' : 'سخت';
    const selectedAnswer = examState.answers[q.id];
    const isMarked = examState.marked[q.id];

    let optionsHtml = '';
    q.shuffledOptions.forEach((opt, idx) => {
        const isSelected = selectedAnswer === opt.originalIndex;
        optionsHtml += `
            <label class="option ${isSelected ? 'selected' : ''}" data-original="${opt.originalIndex}">
                <input type="radio" name="exam-q" value="${opt.originalIndex}" ${isSelected ? 'checked' : ''}>
                <span>${opt.text}</span>
            </label>
        `;
    });

    container.innerHTML = `
        <div class="exam-question">
            <div class="q-header">
                <span class="q-number">سؤال ${examState.currentIndex + 1} از ${examState.questions.length}</span>
                <div>
                    <span class="difficulty ${q.difficulty}">${diffLabel}</span>
                    <button class="mark-btn ${isMarked ? 'marked' : ''}" id="mark-btn" style="margin-right:8px;">${isMarked ? 'علامت‌گذاری شده' : 'علامت‌گذاری'}</button>
                </div>
            </div>
            <div class="q-text">${q.question}</div>
            <div class="options">${optionsHtml}</div>
        </div>
    `;

    container.querySelectorAll('.option').forEach(opt => {
        opt.addEventListener('click', function() {
            const original = parseInt(this.dataset.original);
            examState.answers[q.id] = original;
            container.querySelectorAll('.option').forEach(o => o.classList.remove('selected'));
            this.classList.add('selected');
            this.querySelector('input').checked = true;
            renderPalette();
        });
    });

    const markBtn = document.getElementById('mark-btn');
    if (markBtn) {
        markBtn.addEventListener('click', function() {
            examState.marked[q.id] = !examState.marked[q.id];
            renderExamQuestion();
            renderPalette();
        });
    }

    updateProgress();
}

function updateProgress() {
    const total = examState.questions.length;
    const current = examState.currentIndex + 1;
    const pct = (current / total) * 100;
    document.getElementById('exam-progress-text').textContent = `سؤال ${current} از ${total}`;
    document.getElementById('exam-progress-fill').style.width = pct + '%';

    document.getElementById('prev-btn').disabled = examState.currentIndex === 0;
    document.getElementById('next-btn').disabled = examState.currentIndex === total - 1;
}

function renderPalette() {
    const palette = document.getElementById('question-palette');
    if (!palette) return;
    palette.innerHTML = '';
    examState.questions.forEach((q, idx) => {
        const btn = document.createElement('button');
        btn.className = 'palette-item';
        if (examState.answers[q.id] !== undefined) btn.classList.add('answered');
        if (examState.marked[q.id]) btn.classList.add('marked');
        if (idx === examState.currentIndex) btn.classList.add('current');
        btn.textContent = idx + 1;
        btn.addEventListener('click', () => {
            examState.currentIndex = idx;
            renderExamQuestion();
        });
        palette.appendChild(btn);
    });
}

function finishExam(autoSubmit = false) {
    if (!autoSubmit) {
        const unanswered = examState.questions.filter(q => examState.answers[q.id] === undefined).length;
        const msg = unanswered > 0
            ? `شما ${unanswered} سؤال بی‌پاسخ دارید. آیا مطمئن هستید؟`
            : 'آیا از پایان آزمون مطمئن هستید؟';
        if (!confirm(msg)) return;
    }

    examState.examActive = false;
    if (examState.timerInterval) clearInterval(examState.timerInterval);

    document.getElementById('exam-running').classList.add('hidden');
    document.getElementById('exam-result').classList.remove('hidden');

    renderResults();
}

function renderResults() {
    let correct = 0, wrong = 0, unanswered = 0;
    const topicStats = {};
    const diffStats = { easy: { c: 0, t: 0 }, medium: { c: 0, t: 0 }, hard: { c: 0, t: 0 } };

    examState.questions.forEach(q => {
        const ans = examState.answers[q.id];
        const isCorrect = ans === q.correct;
        if (ans === undefined) unanswered++;
        else if (isCorrect) correct++;
        else wrong++;

        if (!topicStats[q.topic]) topicStats[q.topic] = { c: 0, t: 0 };
        topicStats[q.topic].t++;
        if (isCorrect) topicStats[q.topic].c++;

        if (diffStats[q.difficulty]) {
            diffStats[q.difficulty].t++;
            if (isCorrect) diffStats[q.difficulty].c++;
        }
    });

    const total = examState.questions.length;
    const percent = total > 0 ? Math.round((correct / total) * 100) : 0;
    const score20 = total > 0 ? ((correct / total) * 20).toFixed(2) : '0';

    document.getElementById('result-correct').textContent = correct;
    document.getElementById('result-wrong').textContent = wrong;
    document.getElementById('result-unanswered').textContent = unanswered;
    document.getElementById('result-percent').textContent = percent + '٪';
    document.getElementById('result-score').textContent = score20;
    const m = Math.floor(examState.timeElapsed / 60).toString().padStart(2, '0');
    const s = (examState.timeElapsed % 60).toString().padStart(2, '0');
    document.getElementById('result-time').textContent = `${m}:${s}`;

    const topicLabels = {
        diabetes: 'دیابت', thyroid: 'تیروئید', hypertension: 'فشار خون',
        angina: 'آنژین صدری', 'heart-failure': 'نارسایی قلبی',
        antiarrhythmic: 'ضد آریتمی', 'female-hormones': 'هورمون‌های زنانه',
        'male-hormones': 'هورمون‌های مردانه', other: 'سایر'
    };

    let topicHtml = '';
    Object.keys(topicStats).forEach(t => {
        const st = topicStats[t];
        const p = Math.round((st.c / st.t) * 100);
        const cls = p >= 70 ? 'good' : p >= 40 ? 'medium' : 'bad';
        topicHtml += `
            <div class="analysis-bar">
                <span class="bar-label">${topicLabels[t] || t}</span>
                <div class="bar-track"><div class="bar-fill ${cls}" style="width:${p}%">${p}٪ (${st.c}/${st.t})</div></div>
            </div>
        `;
    });
    document.getElementById('analysis-topic').innerHTML = topicHtml || '<p>داده‌ای موجود نیست.</p>';

    let diffHtml = '';
    ['easy', 'medium', 'hard'].forEach(d => {
        const st = diffStats[d];
        if (st.t === 0) return;
        const p = Math.round((st.c / st.t) * 100);
        const cls = p >= 70 ? 'good' : p >= 40 ? 'medium' : 'bad';
        const label = d === 'easy' ? 'آسان' : d === 'medium' ? 'متوسط' : 'سخت';
        diffHtml += `
            <div class="analysis-bar">
                <span class="bar-label">${label}</span>
                <div class="bar-track"><div class="bar-fill ${cls}" style="width:${p}%">${p}٪ (${st.c}/${st.t})</div></div>
            </div>
        `;
    });
    document.getElementById('analysis-difficulty').innerHTML = diffHtml || '<p>داده‌ای موجود نیست.</p>';

    const weakTopics = Object.keys(topicStats)
        .filter(t => (topicStats[t].c / topicStats[t].t) < 0.5)
        .map(t => topicLabels[t] || t);

    let weaknessHtml = '';
    if (weakTopics.length > 0) {
        weaknessHtml = `<p>مباحث نیازمند مرور:</p><ul>${weakTopics.map(t => `<li>${t}</li>`).join('')}</ul>`;
    } else {
        weaknessHtml = '<p>عملکرد شما در همه مباحث مناسب است. ادامه دهید!</p>';
    }
    document.getElementById('analysis-weakness').innerHTML = weaknessHtml;

    let reviewHtml = '';
    examState.questions.forEach((q, idx) => {
        const ans = examState.answers[q.id];
        const isCorrect = ans === q.correct;
        const status = ans === undefined ? 'unanswered' : (isCorrect ? 'correct' : 'wrong');
        const statusLabel = ans === undefined ? 'بی‌پاسخ' : (isCorrect ? 'صحیح' : 'غلط');
        const userAns = ans !== undefined ? q.options[ans] : '—';
        const correctAns = q.options[q.correct];
        const diffLabel = q.difficulty === 'easy' ? 'آسان' : q.difficulty === 'medium' ? 'متوسط' : 'سخت';

        reviewHtml += `
            <div class="review-question ${status}">
                <div class="q-header">
                    <span class="q-number">سؤال ${idx + 1}</span>
                    <div>
                        <span class="difficulty ${q.difficulty}">${diffLabel}</span>
                        <span class="status-badge ${status}">${statusLabel}</span>
                    </div>
                </div>
                <div class="q-text">${q.question}</div>
                <div style="margin: 10px 0;">
                    <p><strong>پاسخ شما:</strong> ${userAns}</p>
                    <p><strong>پاسخ صحیح:</strong> ${correctAns}</p>
                </div>
                <div class="explanation show">
                    <strong>توضیح:</strong>
                    <p>${q.explanation}</p>
                </div>
            </div>
        `;
    });
    document.getElementById('review-questions').innerHTML = reviewHtml;
}

function retryWrong() {
    const wrongQs = examState.questions.filter(q => examState.answers[q.id] !== q.correct);
    if (wrongQs.length === 0) {
        alert('شما هیچ سؤال غلطی ندارید.');
        return;
    }

    examState.questions = wrongQs.map(q => ({
        ...q,
        shuffledOptions: shuffleArray(q.options.map((opt, i) => ({ text: opt, originalIndex: i })))
    }));
    examState.currentIndex = 0;
    examState.answers = {};
    examState.marked = {};
    examState.startTime = Date.now();
    examState.timeLimit = 0;
    examState.timeElapsed = 0;
    examState.examActive = true;

    document.getElementById('exam-setup').classList.add('hidden');
    document.getElementById('exam-running').classList.remove('hidden');
    document.getElementById('exam-result').classList.add('hidden');

    renderExamQuestion();
    renderPalette();
    startTimer();
}

// ================== توابع نمونه سؤالات و سؤالات تألیفی ==================

function renderQuestions(questions, containerId, showFilters = false) {
    const container = document.getElementById(containerId);
    if (!container) return;

    let filteredQuestions = questions;

    if (showFilters) {
        const topicFilter = document.getElementById('filter-topic')?.value || 'all';
        const difficultyFilter = document.getElementById('filter-difficulty')?.value || 'all';

        if (topicFilter !== 'all') {
            filteredQuestions = filteredQuestions.filter(q => q.topic === topicFilter);
        }
        if (difficultyFilter !== 'all') {
            filteredQuestions = filteredQuestions.filter(q => q.difficulty === difficultyFilter);
        }
    }

    container.innerHTML = '';

    filteredQuestions.forEach((q, index) => {
        const card = document.createElement('div');
        card.className = 'question-card';
        card.dataset.id = q.id;

        const difficultyLabel = q.difficulty === 'easy' ? 'آسان' : q.difficulty === 'medium' ? 'متوسط' : 'سخت';

        let optionsHtml = '';
        q.options.forEach((opt, optIndex) => {
            optionsHtml += `
                <label class="option" data-index="${optIndex}">
                    <input type="radio" name="q${q.id}" value="${optIndex}">
                    <span>${opt}</span>
                </label>
            `;
        });

        card.innerHTML = `
            <div class="q-header">
                <span class="q-number">سؤال ${index + 1}</span>
                <span class="difficulty ${q.difficulty}">${difficultyLabel}</span>
            </div>
            <div class="q-text">${q.question}</div>
            <div class="options">
                ${optionsHtml}
            </div>
            <div class="explanation" id="exp-${q.id}">
                <strong>پاسخ صحیح: گزینه ${q.correct + 1}</strong>
                <p>${q.explanation}</p>
            </div>
        `;

        container.appendChild(card);
    });
}

function submitQuiz(questions, containerId, resultId, scoreId, scoreTextId) {
    const container = document.getElementById(containerId);
    if (!container) return;

    const cards = container.querySelectorAll('.question-card');
    let correctCount = 0;
    let total = 0;

    cards.forEach(card => {
        const qId = parseInt(card.dataset.id);
        const question = questions.find(q => q.id === qId);
        if (!question) return;

        total++;
        const selected = card.querySelector('input[type="radio"]:checked');
        const options = card.querySelectorAll('.option');
        const explanation = card.querySelector('.explanation');

        options.forEach(opt => {
            opt.classList.remove('correct', 'wrong', 'selected');
        });

        if (selected) {
            const selectedIndex = parseInt(selected.value);
            options[selectedIndex].classList.add('selected');

            if (selectedIndex === question.correct) {
                correctCount++;
                options[selectedIndex].classList.add('correct');
            } else {
                options[selectedIndex].classList.add('wrong');
                options[question.correct].classList.add('correct');
            }
        } else {
            options[question.correct].classList.add('correct');
        }

        if (explanation) {
            explanation.classList.add('show');
        }
    });

    const resultDiv = document.getElementById(resultId);
    const scoreDisplay = document.getElementById(scoreId);
    const scoreText = document.getElementById(scoreTextId);

    if (resultDiv) {
        resultDiv.classList.add('show');
        if (scoreDisplay) scoreDisplay.textContent = `${correctCount} از ${total}`;
        if (scoreText) scoreText.textContent = `تعداد پاسخ‌های صحیح: ${correctCount} از ${total}`;
    }

    return { correctCount, total };
}

function resetQuiz(questions, containerId, resultId) {
    const container = document.getElementById(containerId);
    if (container) {
        container.querySelectorAll('input[type="radio"]').forEach(input => {
            input.checked = false;
        });
        container.querySelectorAll('.option').forEach(opt => {
            opt.classList.remove('correct', 'wrong', 'selected');
        });
        container.querySelectorAll('.explanation').forEach(exp => {
            exp.classList.remove('show');
        });
    }

    const resultDiv = document.getElementById(resultId);
    if (resultDiv) {
        resultDiv.classList.remove('show');
    }

    if (questions === sampleQuestions) {
        renderQuestions(sampleQuestions, 'quiz-container', true);
    } else if (typeof authoredQuestions !== 'undefined' && questions === authoredQuestions) {
        renderQuestions(authoredQuestions, 'authored-container', false);
    }
}

// ================== مقداردهی اولیه ==================

document.addEventListener('DOMContentLoaded', function() {
    // بخش نمونه سؤالات
    const quizContainer = document.getElementById('quiz-container');
    const authoredContainer = document.getElementById('authored-container');

    if (quizContainer) {
        renderQuestions(sampleQuestions, 'quiz-container', true);
    }

    if (authoredContainer && typeof authoredQuestions !== 'undefined') {
        renderQuestions(authoredQuestions, 'authored-container', false);
    }

    // Event listeners نمونه سؤالات
    const submitBtn = document.getElementById('submit-quiz');
    const resetBtn = document.getElementById('reset-quiz');
    const topicFilter = document.getElementById('filter-topic');
    const difficultyFilter = document.getElementById('filter-difficulty');

    if (submitBtn) {
        submitBtn.addEventListener('click', function() {
            submitQuiz(sampleQuestions, 'quiz-container', 'quiz-result', 'score-display', 'score-text');
        });
    }

    if (resetBtn) {
        resetBtn.addEventListener('click', function() {
            resetQuiz(sampleQuestions, 'quiz-container', 'quiz-result');
        });
    }

    if (topicFilter) {
        topicFilter.addEventListener('change', function() {
            renderQuestions(sampleQuestions, 'quiz-container', true);
        });
    }

    if (difficultyFilter) {
        difficultyFilter.addEventListener('change', function() {
            renderQuestions(sampleQuestions, 'quiz-container', true);
        });
    }

    // Event listeners سؤالات تألیفی
    const submitAuthoredBtn = document.getElementById('submit-authored');
    const resetAuthoredBtn = document.getElementById('reset-authored');

    if (submitAuthoredBtn && typeof authoredQuestions !== 'undefined') {
        submitAuthoredBtn.addEventListener('click', function() {
            submitQuiz(authoredQuestions, 'authored-container', 'authored-result', 'authored-score-display', 'authored-score-text');
        });
    }

    if (resetAuthoredBtn && typeof authoredQuestions !== 'undefined') {
        resetAuthoredBtn.addEventListener('click', function() {
            resetQuiz(authoredQuestions, 'authored-container', 'authored-result');
        });
    }

    // ================== Event Listeners آزمون ==================
    const startBtn = document.getElementById('start-exam-btn');
    if (startBtn) startBtn.addEventListener('click', setupExam);

    const prevBtn = document.getElementById('prev-btn');
    if (prevBtn) prevBtn.addEventListener('click', () => {
        if (examState.currentIndex > 0) {
            examState.currentIndex--;
            renderExamQuestion();
        }
    });

    const nextBtn = document.getElementById('next-btn');
    if (nextBtn) nextBtn.addEventListener('click', () => {
        if (examState.currentIndex < examState.questions.length - 1) {
            examState.currentIndex++;
            renderExamQuestion();
        }
    });

    const finishBtn = document.getElementById('finish-exam-btn');
    if (finishBtn) finishBtn.addEventListener('click', () => finishExam(false));

    const retryBtn = document.getElementById('retry-wrong-btn');
    if (retryBtn) retryBtn.addEventListener('click', retryWrong);

    const newBtn = document.getElementById('new-exam-btn');
    if (newBtn) newBtn.addEventListener('click', () => {
        document.getElementById('exam-setup').classList.remove('hidden');
        document.getElementById('exam-running').classList.add('hidden');
        document.getElementById('exam-result').classList.add('hidden');
        document.getElementById('setup-message').textContent = '';
    });
});